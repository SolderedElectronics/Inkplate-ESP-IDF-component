/**
 * @file        main.cpp
 * @author      Fran Fodor for Soldered
 * @brief       Hourly weather station using OpenWeatherMap (Inkplate 2).
 *
 * @details     Demonstrates a small battery-friendly weather dashboard for
 *              Inkplate 2. On every wake-up the board connects to WiFi,
 *              synchronizes time via NTP, fetches an hourly forecast from
 *              the OpenWeatherMap "onecall" API for a configured
 *              latitude/longitude, and renders three panels: the current
 *              temperature/icon and the next two hours. The board then goes
 *              into deep sleep and repeats the whole cycle after
 *              DELAY_MS milliseconds (deep sleep resets the ESP32, so
 *              execution always restarts from app_main()).
 *
 * Requirements:
 * - Board:      Soldered Inkplate 2
 * - Framework:  ESP-IDF v6.x
 * - Hardware:   Inkplate 2, USB cable
 * - Extra:      Stable WiFi connection, OpenWeatherMap API key
 *
 * Configuration:
 * - Menuconfig -> Inkplate Boards -> Inkplate2
 * - Menuconfig -> WiFi Configuration -> Enter your SSID and password
 * - main.cpp   -> API_KEY: your OpenWeatherMap API key
 * - main.cpp   -> LOCATION_LAT / LOCATION_LON: coordinates for your location
 *
 * How to use:
 * 1) Create a free OpenWeatherMap API key at https://openweathermap.org/guide
 *    (the "One Call API 3.0" plan is required) and paste it into API_KEY.
 * 2) Set LOCATION_LAT / LOCATION_LON to your location's coordinates.
 * 3) Configure WiFi credentials via menuconfig.
 * 4) Build and flash to Inkplate 2.
 * 5) The board fetches data, renders the dashboard, deep sleeps, and repeats.
 *
 * Expected output:
 * - Display: three framed panels showing "Now" and the next two hour
 *   labels, a temperature value (degC by default) and a small weather icon
 *   per panel.
 * - On WiFi failure: an error message is shown, then the board deep sleeps
 *   briefly before retrying.
 * - Serial Monitor: WiFi/NTP status and weather fetch retries (if any).
 *
 * Notes:
 * - Display uses the Inkplate 2 tri-color palette (INKPLATE2_BLACK /
 *   INKPLATE2_WHITE / INKPLATE2_RED) and a full refresh each cycle.
 * - Only the small (48x48, "_S_") monochrome icon variants from the
 *   original Arduino project are ported - the full-size color icon headers
 *   were unused by the sketch and dropped to avoid bloating the firmware
 *   image (see icons.h).
 * - Unlike the original sketch (which retries forever on a fetch failure),
 *   this port gives up after a handful of retries per wake cycle so a
 *   misconfigured API key/location cannot hang the board awake and drain
 *   the battery; it will simply try again on the next scheduled wake-up.
 * - The original sketch's WiFi-retry sleep passed seconds where the
 *   underlying API expects microseconds (effectively sleeping 10ms instead
 *   of 10s); this port converts DELAY_WIFI_RETRY_MS correctly.
 * - API rate limits apply - verify your current OpenWeatherMap quota before
 *   lowering DELAY_MS.
 * - Icons are selected by matching OpenWeatherMap condition abbreviations
 *   (e.g. "01d", "10n") against the built-in icon table.
 *
 * Docs:         https://docs.soldered.com/inkplate
 * Support:      https://forum.soldered.com/
 * Image tool:   https://tools.soldered.com/tools/image-converter/
 */

