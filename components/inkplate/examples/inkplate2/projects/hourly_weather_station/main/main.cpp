#endif

#include "Inkplate.h"
#include "NetworkFunctions.h"

// Custom font used for the panel labels
#include "Fonts/SourceSansPro_Regular8pt7b.h"

// Small (48x48) weather condition icons generated by iconConvert.py
#include "icons.h"

#include "esp_log.h"
#include "esp_sleep.h"
